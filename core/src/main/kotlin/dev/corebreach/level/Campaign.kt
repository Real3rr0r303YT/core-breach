    fun build(handmade: List<LevelData>): List<LevelData> {
        val usedNames = handmade.map { it.name }.toMutableSet()
        return (1..SIZE).map { id ->
            val boss = BossType.forLevel(id)
            when {
                id <= handmade.size -> handmade[id - 1]
                boss != null -> LevelData(id, boss.title, ARENAS.getValue(boss), speed(id), boss)
                else -> generate(id, usedNames)
            }
        }
    }

    /** Daemon-Tempo steigt ueber die Kampagne von 1.0x auf ca. 1.6x. */
    private fun speed(id: Int): Float = 1f + (id - 1) * 0.006f

    private fun generate(id: Int, usedNames: MutableSet<String>): LevelData {
        val rnd = Random(0xC0DE + id * 7919)

        // Schwierigkeitskurve: mehr Chunks, hoehere Tiers
        val count = 3 + id / 10
        val maxTier = minOf(5, 1 + (id + 5) / 20)
        val minTier = maxOf(1, maxTier - 1)

        val interior = Array(10) { StringBuilder() }
        fun append(cols: List<String>) = cols.forEachIndexed { i, r -> interior[i].append(r) }
        fun flat(width: Int, mark: Char = '.', gate: Boolean = false) = List(10) { i ->
            when {
                i == 9 && mark != '.' -> ".".repeat(width / 2 - 1) + mark + ".".repeat(width - width / 2)
                // Reset-Feld ueber die volle Hoehe: wer nach einem Gravity-Chunk noch oben klebt, faellt hier zurueck
                gate -> ".".repeat(width / 2) + Tile.GRAVITY_RESET + ".".repeat(width - width / 2 - 1)
                else -> ".".repeat(width)
            }
        }

        append(flat(3, 'P'))
        var last = -1
        for (n in 0 until count) {
            val pool = CHUNKS.indices.filter { CHUNKS[it].tier in minTier..maxTier && it != last }
            val pick = pool[rnd.nextInt(pool.size)]
            last = pick
            append(CHUNKS[pick].rows)
            // Checkpoint nach jedem dritten Chunk in langen Leveln
            val checkpoint = count >= 6 && n % 3 == 2 && n < count - 1
            val gravity = CHUNKS[pick].rows.any { Tile.GRAVITY in it }
            append(flat(3, if (checkpoint) Tile.CHECKPOINT else '.', gate = gravity))
        }
        append(flat(3, 'X'))

        // Genau 3 Shards, gleichmaessig ueber das Level verteilt
        val slots = ArrayList<Pair<Int, Int>>()
        for (r in 0 until 10) interior[r].forEachIndexed { x, c -> if (c == 's') slots += r to x }
        slots.sortBy { it.second }
        val chosen = setOf(slots[slots.size / 6], slots[slots.size / 2], slots[slots.size * 5 / 6])
        for ((r, x) in slots) interior[r].setCharAt(x, if ((r to x) in chosen) Tile.SHARD else Tile.EMPTY)

        val width = interior[0].length + 2
        val rows = ArrayList<String>()
        rows += "#".repeat(width)
        for (r in 0 until 10) rows += "#" + interior[r] + "#"
        rows += "#".repeat(width)

        var name: String
        do {
            name = PREFIX[rnd.nextInt(PREFIX.size)] + "." + SUFFIX[rnd.nextInt(SUFFIX.size)]
        } while (!usedNames.add(name))

        return LevelData(id, name, rows, speed(id))
    }
